func TestUploaderReviewLocalPostgres(t *testing.T) {
	if os.Getenv("YOUBAN_UPLOADER_REVIEW_LOCAL_PG") != "1" {
		t.Skip("requires upgraded local youban_tgfake_test")
	}
	ctx, cancel := context.WithTimeout(context.Background(), 20*time.Second)
	defer cancel()
	node := gdb.ConfigNode{Type: "pgsql", Host: "127.0.0.1", Port: "5432", User: "postgres", Pass: os.Getenv("PGPASSWORD"), Name: "youban_tgfake_test"}
	root, err := gdb.New(node)
	if err != nil {
		t.Fatal(err)
	}
	schema := fmt.Sprintf("uploader_review_test_%d", time.Now().UnixNano())
	if _, err := root.Exec(ctx, "CREATE SCHEMA "+schema); err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() {
		if _, err := root.Exec(context.Background(), "DROP SCHEMA "+schema+" CASCADE"); err != nil {
			t.Error(err)
		}
	})
	before := gdb.GetConfig("default")
	t.Cleanup(func() { gdb.SetConfigGroup("default", before) })
	node.Namespace = schema
	gdb.SetConfigGroup("default", gdb.ConfigGroup{node})
	db := g.DB()
	if db.GetConfig().Type != "pgsql" || db.GetConfig().Namespace != schema {
		t.Fatal("run this test by itself to isolate the GoFrame database singleton")
	}
	t.Cleanup(func() { _ = db.GetCore().ClearTableFieldsAll(context.Background()) })
	if !cache.Initialized() {
		adapter := g.Cfg().GetAdapter().(*gcfg.AdapterFile)
		original := g.Cfg().MustGet(ctx, "cache.adapter").Val()
		if err := adapter.Set("cache.adapter", "memory"); err != nil {
			t.Fatal(err)
		}
		cache.SetAdapter(ctx)
		if err := adapter.Set("cache.adapter", original); err != nil {
			t.Fatal(err)
		}
	}
	previousCache := cache.Instance().GetAdapter()
	cache.Instance().SetAdapter(gcache.NewAdapterMemory())
	t.Cleanup(func() { cache.Instance().SetAdapter(previousCache) })
	exec := func(sql string) {
		t.Helper()
		if _, err := db.Exec(ctx, sql); err != nil {
			t.Fatal(err)
		}
	}
	for _, table := range []string{
		uploaderReviewTable, "hg_youban_bot_role_registry", botTable, userTable, accountBindTbl,
		"hg_youban_publish_bot", "hg_youban_publish_account_notice", "hg_youban_publish_account",
		"hg_youban_publish_tenant", "hg_youban_publish_account_setting", "hg_youban_publish_account_visibility",
		"hg_youban_publish_profile_review", "hg_content_profile", "hg_youban_publish_profile_state",
		"hg_youban_publish_note_index", "hg_youban_publish_note_search",
	} {
		exec("CREATE TABLE " + table + " (LIKE public." + table + " INCLUDING ALL)")
	}
	for _, table := range []string{
		uploaderReviewTable, "hg_youban_publish_account_notice", "hg_youban_publish_account", "hg_youban_publish_account_setting",
		userTable, accountBindTbl, "hg_youban_publish_profile_review", "hg_youban_publish_note_index", "hg_youban_publish_note_search",
	} {
		exec("ALTER TABLE " + table + " ALTER COLUMN id DROP DEFAULT")
		exec("ALTER TABLE " + table + " ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY")
	}
	exec("INSERT INTO hg_youban_publish_tenant(id,name) VALUES(1,'审核测试租户')")
	exec(`INSERT INTO hg_youban_publish_account(id,tenant_id,merchant_id,parent_id,account_type,username,nickname,status)
		VALUES(99,1,1,0,'admin','owner','owner',1),(100,1,1,99,'uploader','review_collision','collision',1)`)
	exec(`INSERT INTO hg_youban_publish_bot(id,tenant_id,account_id,bot_type,bot_token,status) VALUES(7,1,99,'uploader','123:fake',1)`)
	exec(`INSERT INTO hg_youban_bot_role_registry(telegram_bot_id,tenant_id,role,require_registration) VALUES(123,1,'uploader',1)`)
	exec("INSERT INTO " + botTable + "(id,bot_token,is_official,status) VALUES(8,'456:fake',1,1)")
	exec("INSERT INTO " + accountBindTbl + "(app,account_id,telegram_user_id,bot_id,status) VALUES('api',99,'99',8,1)")
	exec("INSERT INTO " + userTable + "(bot_id,telegram_user_id,chat_id,status) VALUES(8,'99','99',1)")
	if err := db.GetCore().ClearTableFieldsAll(ctx); err != nil {
		t.Fatal(err)
	}

	previous := ps.SysPublish()
	ps.RegisterSysPublish(publishlogic.NewSysPublish())
	t.Cleanup(func() { ps.RegisterSysPublish(previous) })
	s := &sSysBot{}
	bot, err := collectorBotByID(ctx, 7)
	if err != nil {
		t.Fatal(err)
	}
	assertCount := func(query string, want int) {
		t.Helper()
		count, err := db.GetCount(ctx, query)
		if err != nil || count != want {
			t.Fatalf("count %d, want %d, query %s, err %v", count, want, query, err)
		}
	}
	for _, id := range []int64{11, 11, 12, 13} {
		username := "review_test"
		if id == 11 {
			username = "review_collision"
		}
		review, err := s.submitUploaderReview(ctx, bot, &models.User{ID: id, FirstName: "测试", LastName: "用户", Username: username})
		if err != nil || review == nil || review.Status != uploaderPending {
			t.Fatalf("submit %d: %+v, %v", id, review, err)
		}
	}
	assertCount("SELECT count(*) FROM hg_youban_publish_account_notice WHERE category='uploader_review_request' AND status='bot_pending' AND created_at IS NOT NULL", 3)
	assertCount("SELECT count(*) FROM hg_youban_publish_account", 2)
	review, err := uploaderReviewByUser(ctx, bot, 11)
	if err != nil || review == nil {
		t.Fatalf("lookup: %+v, %v", review, err)
	}
	decide := func(id, actor int64, action, want string) {
		t.Helper()
		got, err := s.decideUploaderReview(ctx, id, actor, action)
		if err != nil || got != want {
			t.Fatalf("decide %d by %d: %q, want %q, err %v", id, actor, got, want, err)
		}
	}
	type sendRequest struct {
		path, chat, text, markup string
	}
	sent := make(chan sendRequest, 5)
	telegram := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		sent <- sendRequest{r.URL.Path, r.FormValue("chat_id"), r.FormValue("text"), r.FormValue("reply_markup")}
		_, _ = fmt.Fprint(w, `{"ok":true,"result":{"message_id":1}}`)
	}))
	t.Cleanup(telegram.Close)
	var previousGateway gs.IGateway
	func() { defer func() { _ = recover() }(); previousGateway = gs.Gateway() }()
	gs.RegisterGateway(accountRenewalTestGateway{client: func(_ context.Context, token string) (*tgbot.Bot, error) {
		return tgbot.New(token, tgbot.WithSkipGetMe(), tgbot.WithServerURL(telegram.URL))
	}})
	t.Cleanup(func() { gs.RegisterGateway(previousGateway) })
	assertDelivery := func(kind string, accountID, reviewID int64, status int, path, chat, text string) {
		t.Helper()
		if err := s.DeliverUploaderReviewNotice(ctx, &pi.UploaderReviewNotice{
			Kind: kind, TenantID: 1, AccountID: accountID, ReviewID: reviewID, Status: status,
		}); err != nil {
			t.Fatal(err)
		}
		select {
		case got := <-sent:
			if !strings.Contains(got.path, path) || strings.Trim(got.chat, "\"") != chat || !strings.Contains(got.text, text) {
				t.Fatalf("notification dispatched to wrong Bot or recipient: %+v", got)
			}
			if kind == pi.UploaderReviewRequestNotice && (!strings.Contains(got.markup, "upr:approve:") || !strings.Contains(got.markup, "upr:reject:")) {
				t.Fatalf("missing review actions: %s", got.markup)
			}
		default:
			t.Fatal("no Telegram notification received")
		}
	}
	assertDelivery(pi.UploaderReviewRequestNotice, 99, review.Id, 0, "456:fake", "99", "申请人昵称：测试 用户\n申请人用户名：@review_collision")
	decide(review.Id, 100, "approve", "申请不存在或当前账号无权审批")
	decide(review.Id, 99, "approve", "已通过")
	decide(review.Id, 99, "approve", "该申请已处理")
	assertDelivery(pi.UploaderReviewResultNotice, 99, review.Id, 0, "123:fake", "11", "注册申请已通过")
	review, err = uploaderReviewByUser(ctx, bot, 11)
	if err != nil || review == nil || review.Status != uploaderApproved || review.AccountId <= 0 {
		t.Fatalf("approved review: %+v, %v", review, err)
	}
	account, err := db.GetOne(ctx, "SELECT * FROM hg_youban_publish_account WHERE id=?", review.AccountId)
	if err != nil || !strings.HasPrefix(account["username"].String(), "tg_") ||
		account["parent_id"].Int64() != 99 || account["password_hash"].IsEmpty() {
		t.Fatalf("collision fallback or account persistence failed: %v", err)
	}
	capability, err := ps.SysPublish().AccountCapability(ctx, "api", review.AccountId)
	if err != nil || capability.TelegramBindingEnabled != 1 || capability.SharedResourceEnabled != 0 ||
		capability.GroupPushEnabled != 0 || capability.ProfileDetailViewEnabled != 0 {
		t.Fatalf("incorrect capability: %+v, %v", capability, err)
	}
	review12, err := uploaderReviewByUser(ctx, bot, 12)
	if err != nil || review12 == nil {
		t.Fatalf("lookup: %+v, %v", review12, err)
	}
	exec("ALTER TABLE hg_youban_publish_account_notice ADD CONSTRAINT fail_review_delivery CHECK (category <> 'uploader_review_result') NOT VALID")
	if _, err := s.decideUploaderReview(ctx, review12.Id, 99, "approve"); err == nil {
		t.Fatal("expected outbox insert failure")
	}
	assertCount("SELECT count(*) FROM hg_youban_publish_account WHERE telegram_user_id='12'", 0)
	assertCount("SELECT count(*) FROM "+uploaderReviewTable+" WHERE telegram_user_id=12 AND status='pending'", 1)
	exec("ALTER TABLE hg_youban_publish_account_notice DROP CONSTRAINT fail_review_delivery")
	decide(review12.Id, 99, "approve", "已通过")
	assertCount("SELECT count(*) FROM hg_youban_publish_account WHERE username='review_test' AND telegram_user_id='12'", 1)
	review13, err := uploaderReviewByUser(ctx, bot, 13)
	if err != nil || review13 == nil {
		t.Fatalf("lookup: %+v, %v", review13, err)
	}
	decide(review13.Id, 99, "reject", "已拒绝")
	assertDelivery(pi.UploaderReviewResultNotice, 99, review13.Id, 0, "123:fake", "13", "未通过")
	assertCount("SELECT count(*) FROM hg_youban_publish_account WHERE telegram_user_id='13'", 0)
	auth := quickPushMediaUploadContext(ctx, 99)
	for i, status := range []int{2, 2, 1} {
		in := &pi.AccountSaveInp{Id: review.AccountId, Username: account["username"].String(), AccountType: pi.PublishAccountTypeUploader, Status: status}
		if _, err := ps.SysPublish().AdminAccountSave(auth, in); err != nil {
			t.Fatal(err)
		}
		if i == 0 {
			assertDelivery(pi.UploaderAccountStatusNotice, review.AccountId, 0, 2, "123:fake", "11", "上架账户已停用")
		}
		if status == 1 {
			assertDelivery(pi.UploaderAccountStatusNotice, review.AccountId, 0, 1, "123:fake", "11", "上架账户已启用")
		}
	}
	assertCount("SELECT count(*) FROM hg_youban_publish_account_notice WHERE category='uploader_review_result'", 3)
	assertCount("SELECT count(*) FROM hg_youban_publish_account_notice WHERE category='uploader_account_status'", 2)
	assertCount("SELECT count(*) FROM "+accountBindTbl, 1)

	exec("INSERT INTO hg_youban_publish_bot(id,tenant_id,account_id,bot_type,bot_token,status) VALUES(9,1,99,'uploader','789:fake',1)")
	exec("INSERT INTO hg_youban_bot_role_registry(telegram_bot_id,tenant_id,role,require_registration) VALUES(789,1,'uploader',1)")
	secondBot, err := collectorBotByID(ctx, 9)
	if err != nil {
		t.Fatal(err)
	}
	ownerUser := &models.User{ID: 99, Username: "owner_personal"}
	personal, err := s.resolveCollectorAccount(ctx, bot, ownerUser, true)
	if err != nil || personal == nil || personal.AccountId == 99 || personal.AccountType != pi.PublishAccountTypeUploader {
		t.Fatalf("direct provisioning used official admin binding: %+v, %v", personal, err)
	}
	second, err := s.resolveCollectorAccount(ctx, secondBot, ownerUser, true)
	if err != nil || second == nil || second.AccountId != personal.AccountId {
		t.Fatalf("second Bot should reuse personal account: %+v, %v", second, err)
	}
	secondReview, err := s.submitUploaderReview(ctx, secondBot, &models.User{ID: 11, Username: "review_collision"})
	if err != nil {
		t.Fatal(err)
	}
	decide(secondReview.Id, 99, "approve", "已通过")
	reused, err := uploaderReviewByUser(ctx, secondBot, 11)
	if err != nil || reused == nil || reused.AccountId != review.AccountId {
		t.Fatalf("second approval should reuse personal account: %+v, %v", reused, err)
	}
	assertCount("SELECT count(*) FROM "+accountBindTbl+" WHERE telegram_user_id='99' AND account_id=99 AND bot_id=8", 1)

	const profileID = 987654321
	exec("UPDATE hg_youban_publish_bot SET require_publish_review=1 WHERE id=7")
	exec(fmt.Sprintf("INSERT INTO hg_content_profile(id,profile_no,title,status,visibility) VALUES(%d,'A98765','待审测试',2,'private')", profileID))
	exec(fmt.Sprintf("INSERT INTO hg_youban_publish_profile_state(profile_id,account_id,tenant_id) VALUES(%d,%d,1)", profileID, review.AccountId))
	submission := &pi.BotProfileReviewSubmit{BotID: 7, TenantID: 1, AccountID: review.AccountId, ProfileNo: "A98765", ChatID: "11", Applicant: "申请测试"}
	if err := ps.SysPublish().SubmitBotProfileReview(ctx, submission); err != nil {
		t.Fatal(err)
	}
	if err := ps.SysPublish().SubmitBotProfileReview(ctx, submission); err == nil {
		t.Fatal("duplicate profile review accepted")
	}
	assertCount("SELECT count(*) FROM hg_content_profile WHERE id=987654321 AND status=3 AND visibility='private'", 1)
	assertCount("SELECT count(*) FROM hg_youban_publish_account_notice WHERE category='profile_review_request' AND status='bot_pending'", 1)
	if _, err := ps.SysPublish().BotProfileStatus(ctx, &pi.BotProfileStatusInp{TenantId: 1, AccountId: review.AccountId, Ids: []int64{profileID}, Status: 1}); err == nil {
		t.Fatal("pending review accepted direct publication")
	}
	if _, err := ps.SysPublish().HandleBotProfileReview(ctx, 1, 100, "approve"); err == nil {
		t.Fatal("unrelated admin accepted")
	}
	if _, err := ps.SysPublish().HandleBotProfileReview(ctx, 1, 99, "preview"); err != nil {
		t.Fatal(err)
	}
	if _, err := ps.SysPublish().HandleBotProfileReview(ctx, 1, 99, "reject"); err != nil {
		t.Fatal(err)
	}
	assertCount("SELECT count(*) FROM hg_content_profile WHERE id=987654321 AND status=2 AND review_status='rejected'", 1)
	if err := ps.SysPublish().SubmitBotProfileReview(ctx, submission); err != nil {
		t.Fatal(err)
	}
	approved, err := ps.SysPublish().HandleBotProfileReview(ctx, 2, 99, "approve")
	if err != nil {
		t.Fatal(err)
	}
	if err := s.DeliverBotProfileApproval(ctx, approved); err != nil {
		t.Fatal(err)
	}
	select {
	case got := <-sent:
		if !strings.Contains(got.path, "123:fake") || strings.Trim(got.chat, "\"") != "11" ||
			!strings.Contains(got.text, "资料审核已通过") || !strings.Contains(got.text, "A98765") {
			t.Fatalf("approval notice sent to wrong destination: %+v", got)
		}
	default:
		t.Fatal("missing approval notice")
	}
	assertCount("SELECT count(*) FROM hg_content_profile WHERE id=987654321 AND status=2 AND review_status='approved'", 1)
	assertCount("SELECT count(*) FROM hg_youban_publish_account_notice WHERE category='profile_review_publish' AND status='bot_pending'", 1)
	assertCount("SELECT count(*) FROM hg_youban_publish_account_notice WHERE category='profile_review_approved' AND status='bot_pending'", 1)
}
